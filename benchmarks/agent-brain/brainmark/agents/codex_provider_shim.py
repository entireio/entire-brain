"""A PATH shim that gives `codex` its provider config when the caller gives none.

WHY THIS EXISTS
---------------
entire-brain's distill shells out to codex as

    codex exec ... --ignore-user-config

with NO model-provider configuration of its own (`internal/cli/distill.go:117`):
it has no Azure plumbing at all, and `--ignore-user-config` means
`~/.codex/config.toml` cannot supply it either. Run unaided on a machine whose
codex is logged into ChatGPT, a distill therefore authenticates against **public
OpenAI** rather than the Azure deployment the run is pinned to. That is not a
crash -- it succeeds, and produces facts from an unpinned model on an unpinned
account. Every number derived from it would be attributed to the wrong model.

The fix is a shim first on PATH that injects exactly the provider config
`CodexAdapter.azure_config_args()` builds, and injects it **only when the caller
supplied none**. That conditional is the whole safety property:

  * a caller that already passes `model_provider=...` -- which is every session
    BrainMark measures, because `CodexAdapter.build_command()` always does -- is
    passed through byte-for-byte and is never touched by this file;
  * a caller that passes nothing -- distill -- gets the pinned provider instead
    of a silent fallback to whatever account the machine is logged into.

It is a HARNESS HELPER, not a hack: it is written from the same backends.json
pins as the measured sessions, its exact bytes are hashed into packet
provenance, and it is installed per data-root so it cannot leak into an
unrelated process.

WHY A SHIM AND NOT A FLAG: distill builds its own argv; BrainMark cannot pass
codex flags through it. PATH is the only injection point that does not require
changing entire-brain, and changing the product to suit the benchmark is exactly
what a benchmark must not do.

FAIRNESS: this touches the `full_brain` arm's PREP step only, and it changes
WHICH ENDPOINT that step authenticates against -- never what any measured
session is told. No arm's prompt, tool set, or instructions are affected.
"""

from __future__ import annotations

import os
import pathlib
import shutil
import stat
from typing import Any

if __package__ in (None, ""):  # pragma: no cover
    import sys

    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2]))
    from brainmark import _harness  # type: ignore[no-redef]
    from brainmark.agents.codex_adapter import CodexAdapter
    from brainmark.agents.base import AgentBackendError  # type: ignore[no-redef]
else:
    from .. import _harness
    from .codex_adapter import CodexAdapter
    from .base import AgentBackendError

SHIM_NAME = "codex"
#: Set by the shim so a child process can tell it is running under one.
MARKER_ENV = "BRAINMARK_CODEX_SHIM"

#: `$@` is re-exec'd verbatim in the pass-through branches, so a caller that
#: already configures a provider is byte-identical to running codex directly.
_TEMPLATE = """\
#!/usr/bin/env bash
# GENERATED by brainmark/agents/codex_provider_shim.py -- do not edit by hand.
#
# Injects the pinned model provider into `codex exec` invocations that carry no
# provider config of their own (entire-brain's distill). Any caller that already
# passes model_provider= is exec'd through untouched.
set -uo pipefail

REAL={real}

# Pass through: the caller configured a provider itself (every measured
# BrainMark session does), so this shim must not second-guess it.
for arg in "$@"; do
  case "$arg" in
    model_provider=*|--model-provider) exec "$REAL" "$@" ;;
  esac
done

# Pass through: only `exec` is injected into. Subcommands like `login` or
# `--version` must behave exactly as the real CLI does.
if [ "${{1:-}}" != "exec" ]; then exec "$REAL" "$@"; fi
shift

export {key_env}={key_env_value}
export {marker}=1
exec "$REAL" exec {provider_args} "$@"
"""


def _shell_quote(value: str) -> str:
    """Single-quote for bash, escaping any embedded single quote."""
    return "'" + str(value).replace("'", "'\\''") + "'"


def find_real_codex(shim_dir: pathlib.Path,
                    env: dict[str, str] | None = None) -> pathlib.Path:
    """The real `codex`, resolved with the shim's own directory removed from PATH.

    Without the exclusion the shim would resolve to itself and fork-bomb; the
    failure would be a hang, not an error, so it is guarded rather than trusted.
    """
    path = (env or os.environ).get("PATH", "")
    shim_dir = pathlib.Path(shim_dir).resolve()
    pruned = os.pathsep.join(
        entry for entry in path.split(os.pathsep)
        if entry and pathlib.Path(entry).expanduser().resolve(strict=False) != shim_dir
    )
    found = shutil.which(SHIM_NAME, path=pruned)
    if not found:
        raise AgentBackendError(
            "codex provider shim: no real `codex` on PATH (excluding the shim dir). "
            "The full_brain arm's distill cannot run without the codex CLI."
        )
    resolved = pathlib.Path(found).resolve()
    if resolved.parent == shim_dir:
        raise AgentBackendError(
            f"codex provider shim: refusing to point at itself ({resolved})"
        )
    return resolved


def write_shim(shim_dir: pathlib.Path, azure: dict[str, Any],
               env: dict[str, str] | None = None,
               real_codex: pathlib.Path | None = None) -> dict[str, Any]:
    """Write `<shim_dir>/codex` and return its provenance.

    `azure` is exactly what `CodexAdapter.azure_settings()` returns, so the
    shim and the measured sessions are configured from ONE source of truth --
    backends.json. Divergence between them is the failure this signature is
    designed to make impossible.
    """
    shim_dir = pathlib.Path(shim_dir)
    shim_dir.mkdir(parents=True, exist_ok=True)
    real = pathlib.Path(real_codex) if real_codex else find_real_codex(shim_dir, env)

    key_env = str(azure["api_key_env"])
    provider_key = str(azure["provider_key"])
    if not provider_key.replace("_", "").replace("-", "").isalnum():
        # A bare TOML key is [A-Za-z0-9_-]+. Anything else would have to be
        # quoted in the path, which codex then fails to match -- silently.
        raise AgentBackendError(
            f"codex provider shim: provider_key {provider_key!r} is not a bare "
            "TOML key and cannot be used unquoted in a --config path"
        )
    body = _TEMPLATE.format(
        real=_shell_quote(str(real)),
        provider_args=" ".join(_shell_quote(arg) for arg in CodexAdapter({}).azure_config_args(azure)),
        key_env=key_env,
        key_env_value=_shell_quote(str(azure["api_key"])),
        marker=MARKER_ENV,
    )
    shim = shim_dir / SHIM_NAME
    # Set permissions before writing credential-bearing bytes; never follow a link.
    fd = os.open(shim, os.O_WRONLY | os.O_CREAT | os.O_TRUNC | os.O_NOFOLLOW, 0o700)
    with os.fdopen(fd, "w", encoding="utf-8") as stream:
        os.fchmod(stream.fileno(), 0o700)
        stream.write(body)

    return {
        "shim_path": str(shim),
        "shim_sha256": _harness.sha256_file(shim),
        "real_codex": str(real),
        "base_url": azure["base_url"],
        "wire_api": azure["wire_api"],
        "provider_key": azure["provider_key"],
        "api_key_env": key_env,
        # NOTE for a reader of a packet: the api key is written INTO the shim so
        # that distill's child process inherits it even though run.py's env
        # sanitizer strips it. The shim therefore lives under the per-pair
        # scratch data root and never in a results dir.
        "why": ("entire-brain distill (internal/cli/distill.go:117) runs `codex exec "
                "--ignore-user-config` with no provider config, so without this shim it "
                "would authenticate against public OpenAI instead of the pinned Azure "
                "deployment. Injected ONLY when the caller supplies no model_provider."),
    }


def install(shim_dir: pathlib.Path, azure: dict[str, Any],
            env: dict[str, str]) -> tuple[dict[str, str], dict[str, Any]]:
    """Write the shim and return (env with it FIRST on PATH, provenance)."""
    provenance = write_shim(shim_dir, azure, env=env)
    env = dict(env)
    env["PATH"] = os.pathsep.join(
        [str(pathlib.Path(shim_dir)), env.get("PATH", "")]
    ).rstrip(os.pathsep)
    provenance["path_prefix"] = str(pathlib.Path(shim_dir))
    return env, provenance
