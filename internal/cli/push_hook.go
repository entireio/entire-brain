// push_hook.go installs the plugin's own git pre-push hook. The host CLI's
// hook installer (entireio/cli strategy/hooks.go) stays untouched: the team
// decided plugin-specific triggering lives in the plugin, chained beside
// whatever hook already owns the slot. The hook body spawns a detached
// `entire-brain memory notify --event push`, which dispatches the throttled
// fact-store upload — so the trail shows memories together with the commits
// the push delivers.

const (
	pushHookName = "pre-push"
	// pushHookMarker identifies OUR hook file. Deliberately distinct from the
	// host CLI's marker: carrying theirs would make `entire enable` treat our
	// file as its own and overwrite it without a backup.
	pushHookMarker = "# entire-brain push hook"
	// pushHookBackupSuffix is where a pre-existing hook moves; our generated
	// chain line invokes it so it keeps running after ours.
	pushHookBackupSuffix = ".pre-entire-brain"
	// hostHookMarker is the marker the host CLI's own hooks carry
	// (entireHookMarker in entireio/cli strategy/hooks.go).
	hostHookMarker = "Entire CLI hooks"
	// hostBackupSuffix is where the host CLI moves a hook it finds in its
	// slot. Its pre-push chain runs that file by its literal name.
	hostBackupSuffix = ".pre-entire"
	// preCommitSignature marks pre-commit's generated hook wrapper.
	preCommitSignature = "# File generated by pre-commit: https://pre-commit.com"
	// rotatedCopyStampLayout is the timestamp both installers append when a
	// backup they are about to replace has changed: the older one is kept as
	// <backup>.<timestamp>, or <backup>.<timestamp>-<n> on a name clash, and
	// nothing runs it.
	rotatedCopyStampLayout = "20060102T150405Z"
)

// pushHookContent renders our hook. selfPath is this plugin binary's absolute
// path, baked in because git hooks run with the user's PATH: a managed plugin
// install is not on it, and only the `entire` child re-prepends the managed
// dir — a dependency this hook deliberately avoids. The notify runs
// backgrounded with stdin/stdout/stderr detached so it can never consume the
// pre-push ref list, slow the push, or fail it.
func pushHookContent(selfPath string) string {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString(pushHookMarker + "\n")
	b.WriteString("# Tells the local entire-brain plugin that a push is transferring this\n")
	b.WriteString("# repo's commits, so it uploads its fact store (detached, best-effort).\n")
	fmt.Fprintf(&b, "if [ -x %s ]; then\n", shellSingleQuote(selfPath))
	fmt.Fprintf(&b, "  %s memory notify --event push </dev/null >/dev/null 2>&1 &\n", shellSingleQuote(selfPath))
	b.WriteString("fi\n")
	// The chain line is unconditional: [ -x ] makes it a no-op when no backup
	// exists, and one content variant means install never has to re-derive
	// whether a hook was chained. $0-relative, so a copy the host CLI moves
	// aside stops chaining instead of double-running the host's hook.
	b.WriteString("# Chain: run the pre-existing hook with the original stdin and arguments;\n")
	b.WriteString("# its exit code decides the push, exactly as before.\n")
	fmt.Fprintf(&b, "backup=\"$0%s\"\n", pushHookBackupSuffix)
	// The fallback is for one layout: we joined the host's chain from its
	// slot, and the host's uninstall moved us back into the primary. The
	// hook we ran from the slot is still behind the slot's name, and with no
	// slot left nothing else runs it. See strandedChainTarget.
	b.WriteString("# After the Entire CLI's uninstall moved this hook back from its\n")
	b.WriteString("# backup slot, the hook it ran from there is still behind that name.\n")
	fmt.Fprintf(&b, "if [ ! -e \"$backup\" ] && [ ! -e \"$0%s\" ]; then backup=\"$0%s%s\"; fi\n",
		hostBackupSuffix, hostBackupSuffix, pushHookBackupSuffix)
	b.WriteString("if [ -x \"$backup\" ]; then exec \"$backup\" \"$@\"; fi\n")
	return b.String()
}

// strandedChainTarget is the Go side of the hook's fallback chain line: for
// our hook at path with no backup of its own and no host slot beside it, the
// hook it chained to from that slot, if one is there. Empty otherwise.
func strandedChainTarget(path string) string {
	stranded := path + hostBackupSuffix + pushHookBackupSuffix
	if pathExists(path+pushHookBackupSuffix) || pathExists(path+hostBackupSuffix) || !pathExists(stranded) {
		return ""
	}
	return stranded
}

// pathExists follows symlinks, like the hook's [ -e ]: a dangling symlink
// counts as absent, so disconnect restores exactly the hook that runs.
func pathExists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}

// setAsideStrandedChainTarget runs before our hook goes into a primary that
// was not ours, with no copy of ours in the host's slot. A file at the
// fallback's name there was left by an earlier join that something other than
// the host's uninstall undid, and the fallback must not start running it.
// Like a changed backup, it is kept under a timestamped name. A primary that
// is a symlink to it is the hook ours is about to wrap, so then it moves into
// the primary instead.
func setAsideStrandedChainTarget(primary string) error {
	return setAside(primary+hostBackupSuffix+pushHookBackupSuffix, "was left behind by an earlier install and nothing runs it", primary)
}

// setAside keeps a file at path under a rotated name, which nothing runs, and
// says so; why completes the warning's "<name> ..." clause. A file that one of
// live resolves to is a hook that runs: it moves into that hook's place
// instead, so it keeps running and no longer sits at a name of ours, where our
// chain line would run it again.
func setAside(path, why string, live ...string) error {
	if _, err := os.Lstat(path); err != nil {
		return nil
	}
	for _, hook := range live {
		if sameFile(hook, path) {
			return moveIntoLink(path, hook)
		}
	}
	rotated, err := rotateAside(path)
	if err != nil {
		return err
	}
	tui.Warnf(os.Stderr, "entire-brain: %s %s; it was kept as %s", filepath.Base(path), why, rotated)
	return nil
}

// moveIntoLink moves the file at path into hook, which resolves to it: a
// symlink to it is replaced by the file, in one rename. A hard link already
// holds the file, so path just goes. When path is itself a link to the file,
// renaming it could leave hook linking to itself, so hook is pointed at the
// file and path goes.
func moveIntoLink(path, hook string) error {
	if info, err := os.Lstat(hook); err == nil && info.Mode()&os.ModeSymlink == 0 {
		return os.Remove(path)
	}
	info, err := os.Lstat(path)
	if err != nil {
		return err
	}
	if info.Mode()&os.ModeSymlink == 0 {
		if err := os.Rename(path, hook); err != nil {
			return fmt.Errorf("move %s into %s: %w", filepath.Base(path), filepath.Base(hook), err)
		}
	} else if err := relinkToFileOf(hook, path); err != nil {
		return err
	}
	tui.Warnf(os.Stderr, "entire-brain: %s linked to %s; the hook was moved into %s", filepath.Base(hook), filepath.Base(path), filepath.Base(hook))
	return nil
}

// relinkToFileOf points the symlink hook straight at the file the symlink
// path resolves to, then removes path. The new link replaces hook in one
// rename; it is relative when the file sits beside hook.
func relinkToFileOf(hook, path string) error {
	file, err := filepath.EvalSymlinks(path)
	if err != nil {
		return fmt.Errorf("resolve %s: %w", filepath.Base(path), err)
	}
	dir := filepath.Dir(hook)
	if resolvedDir, err := filepath.EvalSymlinks(dir); err == nil && filepath.Dir(file) == resolvedDir {
		file = filepath.Base(file)
	}
	tmp := filepath.Join(dir, ".entire-brain-relink-"+filepath.Base(hook))
	_ = os.Remove(tmp)
	if err := os.Symlink(file, tmp); err != nil {
		return fmt.Errorf("relink %s: %w", filepath.Base(hook), err)
	}
	if err := os.Rename(tmp, hook); err != nil {
		_ = os.Remove(tmp)
		return fmt.Errorf("relink %s: %w", filepath.Base(hook), err)
	}
	return os.Remove(path)
}

// rotateAside renames path to path.<timestamp>, adding -<n> on a name clash,
// the names isRotatedHookCopy recognizes and nothing runs.
func rotateAside(path string) (string, error) {
	base := path + "." + time.Now().UTC().Format(rotatedCopyStampLayout)
	rotated := base
	for n := 1; ; n++ {
		_, err := os.Lstat(rotated)
		if os.IsNotExist(err) {
			break
		}
		if err != nil {
			// A name the filesystem refuses (too long, say) is refused with
			// every -<n> too; only an existing file is a clash.
			return "", fmt.Errorf("rotate %s: %w", filepath.Base(path), err)
		}
		rotated = fmt.Sprintf("%s-%d", base, n)
	}
	if err := os.Rename(path, rotated); err != nil {
		return "", fmt.Errorf("rotate %s: %w", filepath.Base(path), err)
	}
	return rotated, nil
}

// shellSingleQuote wraps s in single quotes, escaping embedded single quotes,
// so an install path with spaces or metacharacters cannot change the script.
func shellSingleQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

type pushHookState string

const (
	pushHookInstalled pushHookState = "installed" // our file written or refreshed in the primary slot
	pushHookChainedIn pushHookState = "chained"   // ours is reachable via another tool's chain; left alone
	pushHookUnchanged pushHookState = "unchanged" // primary already ours with current content
)

// installPushHook puts our pre-push hook in place. Rules, mirroring the host
// CLI's installer but for a GUEST of the slot rather than its owner:
//
//   - no hook: write ours. A copy of ours in the host's backup slot means the
//     host's hook that ran it is gone: that copy moves back into the primary,
//     where its chain line still reaches the hook behind it.
//   - primary carries OUR marker: rewrite only when the content is stale.
//   - OUR marker is reachable at the backup name (the host CLI re-wrapped us —
//     its installer backs up "foreign" hooks and chains to them): do NOTHING.
//     Re-claiming the primary would ping-pong with the host's reconcile; our
//     line still runs via its chain. We refresh the moved copy's content only.
//     A copy rotated to a timestamped name does not count: nothing runs it.
//   - the host CLI's hook in the primary, chaining to a hook in its backup
//     slot: join its chain there. Our hook takes the slot and the hook that
//     was there moves behind ours, so the host's reconcile finds its own hook
//     in the primary and has nothing to re-wrap. Wrapping the primary instead
//     made that reconcile back ours up into the slot, rotating the hook it
//     held to a copy that no longer runs. Our own backup of the primary is
//     set aside first: after the host's uninstall moves us back into the
//     primary, it would run instead of the hook we chained to.
//   - anything else in the slot (the host CLI's hook with nothing chained,
//     husky, a user script, a symlink): move it to the backup name and chain
//     to it. Never chain a file carrying our own marker (self-call), matching
//     the host's guard.
//
// The backup is moved, not copied, so there is exactly one runnable copy of
// the previous hook. A pre-existing DIFFERENT backup rotates to a timestamped
// name that no longer runs, and the install reports it. So does a file left at
// the name the chain line falls back to, when ours goes into a primary that
// was not ours (see setAsideStrandedChainTarget).
func installPushHook(ctx context.Context, opts Options, repoDir string) (pushHookState, string, error) {
	hooksDir, inRepo, err := gitHooksDir(ctx, opts, repoDir)
	if err != nil {
		return "", "", err
	}
	if !inRepo {
		// A shared core.hooksPath (a global ~/.githooks, say) serves EVERY
		// repository at once: a hook written there fires for repos that never
		// connected, and a later uninstall on one repo would strip it for all
		// of them. Managing per-repo state in a shared directory is wrong in
		// both directions, so refuse; uploads ride the daemon tick instead.
		return pushHookSharedDir, hooksDir, nil
	}
	selfPath, err := os.Executable()
	if err != nil {
		return "", "", fmt.Errorf("resolve plugin path: %w", err)
	}
	primary := filepath.Join(hooksDir, pushHookName)

	primaryBytes, primaryErr := readHookFile(primary)
	primaryExists := primaryErr == nil
	if primaryErr != nil && !os.IsNotExist(primaryErr) {
		// A symlinked hook reads through to its target here; only a genuinely
		// unreadable file (or a special file) stops the install.
		return "", "", fmt.Errorf("read %s: %w", primary, primaryErr)
	}
	primaryContent := string(primaryBytes)

	switch {
	case primaryExists && strings.Contains(primaryContent, pushHookMarker):
		want := pushHookContent(selfPath)
		if primaryContent == want {
			return pushHookUnchanged, primary, nil
		}
		if err := writePushHookFile(primary, want); err != nil {
			return "", "", err
		}
		return pushHookInstalled, primary, nil

	case primaryExists:
		// Host re-wrapped us: our hook lives under a backup name and the
		// host's chain runs it. Leave the primary alone; refresh our moved
		// copy so a plugin upgrade's new path still reaches a binary.
		for _, candidate := range movedPushHookCandidates(hooksDir) {
			data, readErr := readHookFile(candidate)
			if readErr != nil || !strings.Contains(string(data), pushHookMarker) {
				continue
			}
			if refreshed := pushHookContent(selfPath); string(data) != refreshed {
				if err := writePushHookFile(candidate, refreshed); err != nil {
					return "", "", err
				}
			}
			return pushHookChainedIn, candidate, nil
		}
		target, targetContent, err := wrapTarget(primary, primaryContent)
		if err != nil {
			return "", "", err
		}
		if err := chainBehind(target, targetContent, selfPath); err != nil {
			return "", "", err
		}
		return pushHookInstalled, target, nil

	default:
		if err := installIntoEmptyPrimary(primary, selfPath); err != nil {
			return "", "", err
		}
		return pushHookInstalled, primary, nil
	}
}

// wrapTarget picks where our hook goes when another hook holds the primary:
// the host's slot when the host's hook chains to it, else the primary. It
// first sets aside the file that would get in the chain line's way there.
func wrapTarget(primary, primaryContent string) (string, string, error) {
	if slot, slotContent, ok := hostChainSlot(primary, primaryContent); ok {
		return slot, slotContent, setAsideOldPrimaryBackup(primary, slot)
	}
	return primary, primaryContent, setAsideStrandedChainTarget(primary)
}

// setAsideOldPrimaryBackup sets aside our backup of the primary, from an
// earlier wrap, when our copy in the host's slot has a hook of its own behind
// it: ours is about to join the host's chain there, or to move out of it into
// the primary. With our hook in the primary, the chain line would run that
// old backup instead of falling back to the hook behind the slot. behind is
// the hook that ends up behind our copy; when it or the primary resolves to
// the backup itself (a symlink to it), the backup is a hook that runs, so it
// moves into that link's place instead.
func setAsideOldPrimaryBackup(primary, behind string) error {
	return setAside(primary+pushHookBackupSuffix, "is an older backup that nothing runs", behind, primary)
}

// sameFile reports whether a and b both exist and resolve to one file.
func sameFile(a, b string) bool {
	ai, err := os.Stat(a)
	if err != nil {
		return false
	}
	bi, err := os.Stat(b)
	return err == nil && os.SameFile(ai, bi)
}

// installIntoEmptyPrimary writes our hook into a missing primary. A copy of
// ours in the host's slot means the host's hook that ran it is gone, so the
// copy moves back into the primary. With no slot beside it, its chain line
// falls back to the hook behind it, as after the host's uninstall. A second
// copy in the primary would chain to nothing, and nothing would run the copy
// in the slot. The move is one rename, so a failure changes nothing; the
// content refresh after it only updates a hook that already runs.
func installIntoEmptyPrimary(primary, selfPath string) error {
	slot := primary + hostBackupSuffix
	if data, err := readHookFile(slot); err == nil && strings.Contains(string(data), pushHookMarker) {
		if pathExists(slot + pushHookBackupSuffix) {
			if err := setAsideOldPrimaryBackup(primary, slot+pushHookBackupSuffix); err != nil {
				return err
			}
		}
		if err := os.Rename(slot, primary); err != nil {
			return fmt.Errorf("move %s hook back into %s: %w", filepath.Base(slot), filepath.Base(primary), err)
		}
		return writePushHookFile(primary, pushHookContent(selfPath))
	}
	if err := setAsideStrandedChainTarget(primary); err != nil {
		return err
	}
	return writePushHookFile(primary, pushHookContent(selfPath))
}

// hostChainSlot returns the host CLI's backup slot and the hook in it when
// the host's pre-push in primary chains to that hook. A slot holding the
// host's own hook, or pre-commit's wrapper, does not qualify: when pre-commit
// runs the host's hook as its legacy hook, the host's chain recognizes its
// wrapper in the slot and skips it, since running it again would fail
// pre-commit's recursion guard. With our hook in the slot, that check would
// miss the wrapper behind it.
func hostChainSlot(primary, primaryContent string) (string, string, bool) {
	slot := primary + hostBackupSuffix
	if !strings.Contains(primaryContent, hostHookMarker) ||
		!strings.Contains(primaryContent, "/"+filepath.Base(slot)+`"`) {
		return "", "", false
	}
	data, err := readHookFile(slot)
	if err != nil {
		return "", "", false
	}
	content := string(data)
	if strings.Contains(content, pushHookMarker) || strings.Contains(content, hostHookMarker) ||
		strings.Contains(content, preCommitSignature) {
		return "", "", false
	}
	return slot, content, true
}

// chainBehind moves the hook at target (whose content is targetContent) to
// target+pushHookBackupSuffix, the name our chain line runs from there, and
// writes ours at target. A target that links to that name is the file there:
// it moves into the link first, so the rename moves the file, not a link to
// itself.
func chainBehind(target, targetContent, selfPath string) error {
	backup := target + pushHookBackupSuffix
	name := filepath.Base(target)
	if sameFile(target, backup) {
		if err := moveIntoLink(backup, target); err != nil {
			return err
		}
	}
	if existing, err := readHookFile(backup); err == nil {
		if string(existing) != targetContent {
			rotated, err := rotateAside(backup)
			if err != nil {
				return err
			}
			tui.Warnf(os.Stderr, "entire-brain: %s changed since it was backed up; the older copy was kept as %s and no longer runs", name, rotated)
		} else if err := os.Remove(backup); err != nil {
			return fmt.Errorf("replace identical backup: %w", err)
		}
	}
	if err := os.Rename(target, backup); err != nil {
		return fmt.Errorf("back up existing %s hook: %w", name, err)
	}
	if err := writePushHookFile(target, pushHookContent(selfPath)); err != nil {
		// Put the original hook back: leaving the slot empty would silently
		// disable the host's pre-push (privacy filtering rides on it).
		if rbErr := os.Rename(backup, target); rbErr != nil {
			return fmt.Errorf("write %s hook: %w; original hook stranded at %s: %v", name, err, backup, rbErr)
		}
		return err
	}
	return nil
}

// pushHookAbsent reports that no hook of ours exists anywhere; refresh-only
// callers (setup) leave the repo untouched in that case.
const pushHookAbsent pushHookState = "absent"

// pushHookDormant reports that the only copies of our hook are ones an
// installer rotated to a timestamped name, which nothing runs. Refresh does
// not install, so it reports this for connect to repair.
const pushHookDormant pushHookState = "dormant"

// pushHookSharedDir reports that core.hooksPath points outside this repo —
// a directory shared across repositories — where per-repo hook management
// must not write or delete anything.
const pushHookSharedDir pushHookState = "shared-hooks-dir"

// refreshPushHook updates an ALREADY-INSTALLED hook (ours in the primary slot
// or moved aside by the host CLI) and never installs a fresh one. Setup owns
// the upgrade beat — the baked selfPath goes stale when the plugin binary
// moves, and the hook's [ -x ] guard turns that into a silent no-op — but
// fresh installs belong to connect: a bare `setup` after a disconnect must
// not resurrect the hook, and setup on a never-connected repo must not move
// other tools' hooks around for a feature that is gated off.
func refreshPushHook(ctx context.Context, opts Options, repoDir string) (pushHookState, string, error) {
	hooksDir, inRepo, err := gitHooksDir(ctx, opts, repoDir)
	if err != nil {
		return "", "", err
	}
	if !inRepo {
		return pushHookSharedDir, hooksDir, nil
	}
	primary := filepath.Join(hooksDir, pushHookName)
	ours := false
	if data, readErr := readHookFile(primary); readErr == nil && strings.Contains(string(data), pushHookMarker) {
		ours = true
	} else {
		for _, candidate := range movedPushHookCandidates(hooksDir) {
			if data, readErr := readHookFile(candidate); readErr == nil && strings.Contains(string(data), pushHookMarker) {
				ours = true
				break
			}
		}
	}
	if !ours {
		if rotated := rotatedPushHookCopies(hooksDir); len(rotated) > 0 {
			return pushHookDormant, rotated[0], nil
		}
		return pushHookAbsent, primary, nil
	}
	return installPushHook(ctx, opts, repoDir)
}

// uninstallPushHook removes our hook. When we hold the primary slot, the
// backup (if any) moves back; when our hook sits further down the chain (the
// host re-wrapped us, or we joined the host's chain), the hook our copy ran
// takes its place, or the copy is deleted when it ran none. Copies an
// installer rotated aside go too. Missing pieces are fine: uninstall is
// idempotent.
func uninstallPushHook(ctx context.Context, opts Options, repoDir string) error {
	hooksDir, inRepo, err := gitHooksDir(ctx, opts, repoDir)
	if err != nil {
		return err
	}
	if !inRepo {
		// Install refuses shared dirs, so there is nothing of ours to remove —
		// and removing anything there would act on every repo sharing the dir.
		return nil
	}
	if err := removeLivePushHook(hooksDir); err != nil {
		return err
	}
	for _, rotated := range rotatedPushHookCopies(hooksDir) {
		if err := os.Remove(rotated); err != nil {
			return err
		}
	}
	return nil
}

// removeLivePushHook takes the copy of our hook that runs out of the chain.
func removeLivePushHook(hooksDir string) error {
	primary := filepath.Join(hooksDir, pushHookName)
	if data, err := readHookFile(primary); err == nil && strings.Contains(string(data), pushHookMarker) {
		return removePrimaryPushHook(primary)
	}
	for _, candidate := range movedPushHookCandidates(hooksDir) {
		data, err := readHookFile(candidate)
		if err != nil || !strings.Contains(string(data), pushHookMarker) {
			continue
		}
		return removeMovedPushHook(candidate, primary)
	}
	return nil
}

// removePrimaryPushHook removes our hook from the primary and puts back the
// hook it ran: its own backup, or the hook behind the host's slot after the
// host's uninstall moved us back from there. Without either, it just goes.
func removePrimaryPushHook(primary string) error {
	restore := ""
	if _, err := os.Stat(primary + pushHookBackupSuffix); err == nil {
		restore = primary + pushHookBackupSuffix
	} else {
		// The host's uninstall moved us back from its slot; the hook we
		// ran from there is the one to restore.
		restore = strandedChainTarget(primary)
	}
	// Remove first: on Windows, rename cannot replace an existing file.
	if err := os.Remove(primary); err != nil || restore == "" {
		return err
	}
	return os.Rename(restore, primary)
}

// removeMovedPushHook removes our copy at candidate, further down a chain.
// Our copy runs the hook behind it when we joined the host's chain (or a host
// re-wrap kept that hook there): it takes our copy's place, so the chain that
// ran us runs it. Rename replaces our copy in one step. Without one, delete
// our copy; the host's chain call is [ -x ]-guarded, so a missing chain
// target is a clean no-op.
func removeMovedPushHook(candidate, primary string) error {
	if _, err := os.Lstat(candidate + pushHookBackupSuffix); err == nil {
		if err := os.Rename(candidate+pushHookBackupSuffix, candidate); err != nil {
			return err
		}
	} else if err := os.Remove(candidate); err != nil {
		return err
	}
	// Our old backup (the host hook we once wrapped) is a DORMANT stale
	// copy: nothing runs it once our hook left the primary. Renaming it
	// into the candidate slot would put a second host pre-push back into
	// the live chain and run it twice, so it is deleted. A restored
	// candidate or a primary that resolves to it (a symlink to it) runs it,
	// so then it stays.
	backup := primary + pushHookBackupSuffix
	if _, err := os.Stat(backup); err == nil && !sameFile(candidate, backup) && !sameFile(primary, backup) {
		return os.Remove(backup)
	}
	return nil
}

// readHookFile reads a hook path after confirming it resolves to a regular
// file (Stat follows symlinks, so a symlinked hook still reads through).
// os.ReadFile alone would block forever on a FIFO or device sitting at a
// repo-controlled hook path.
func readHookFile(path string) ([]byte, error) {
	info, err := os.Stat(path)
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() {
		return nil, fmt.Errorf("%s is not a regular file", path)
	}
	return os.ReadFile(path)
}

// movedPushHookCandidates lists where another installer may have moved our
// hook: every pre-push sibling except the primary, our own backup slot, and
// copies rotated to a timestamped name, which nothing runs.
func movedPushHookCandidates(hooksDir string) []string {
	var out []string
	for _, m := range pushHookSiblings(hooksDir) {
		if m == filepath.Join(hooksDir, pushHookName)+pushHookBackupSuffix || isRotatedHookCopy(m) {
			continue
		}
		out = append(out, m)
	}
	return out
}

// rotatedPushHookCopies lists copies of OUR hook that an installer rotated to
// a timestamped name. The host CLI does this to our hook when it finds a
// different hook in its slot (husky rewrites it on every install) while ours
// is its backup.
func rotatedPushHookCopies(hooksDir string) []string {
	var out []string
	for _, m := range pushHookSiblings(hooksDir) {
		if !isRotatedHookCopy(m) {
			continue
		}
		if data, err := readHookFile(m); err == nil && strings.Contains(string(data), pushHookMarker) {
			out = append(out, m)
		}
	}
	return out
}

// pushHookSiblings lists the <hooksDir>/pre-push.* paths, sorted. It reads
// the directory rather than globbing, so a hooks path holding glob syntax
// (a [ in a directory name) still matches.
func pushHookSiblings(hooksDir string) []string {
	entries, _ := os.ReadDir(hooksDir)
	var out []string
	for _, e := range entries {
		if strings.HasPrefix(e.Name(), pushHookName+".") {
			out = append(out, filepath.Join(hooksDir, e.Name()))
		}
	}
	return out
}

// isRotatedHookCopy reports whether path is <name>.<timestamp>[-<n>], the
// name both the host CLI and installPushHook give an older backup they keep
// aside. Nothing runs such a copy.
func isRotatedHookCopy(path string) bool {
	name := filepath.Base(path)
	dot := strings.LastIndexByte(name, '.')
	if dot < 0 {
		return false
	}
	stamp := name[dot+1:]
	if dash := strings.IndexByte(stamp, '-'); dash >= 0 {
		n := stamp[dash+1:]
		if n == "" || strings.Trim(n, "0123456789") != "" {
			return false
		}
		stamp = stamp[:dash]
	}
	_, err := time.Parse(rotatedCopyStampLayout, stamp)
	return err == nil
}

// writePushHookFile is atomic (temp-and-rename via writeFileAtomic) so a
// symlink sitting at the hook path is replaced rather than written through,
// a crash never leaves a half-written executable hook, and the dot-prefixed
// random temp name can never collide with a concurrent installer or match
// pushHookSiblings' pre-push. prefix.
func writePushHookFile(path, content string) error {
	return brainstore.WriteFileAtomic(path, []byte(content), 0o755) //nolint:gosec // git hooks must be executable
}

// gitHooksDir is realGitHooksDir (git_harden.go — the resolver lives beside
// the pin it reads around) plus creation: installers need the directory to
// exist.
func gitHooksDir(ctx context.Context, opts Options, repoDir string) (string, bool, error) {
	dir, inRepo, err := realGitHooksDir(ctx, opts.Runner, repoDir)
	if err != nil {
		return "", false, err
	}
	if !inRepo {
		// Never create a shared hooks directory on a repo's behalf.
		return dir, false, nil
	}
	if err := os.MkdirAll(dir, 0o755); err != nil { //nolint:gosec // hooks dirs are 0755 by convention
		return "", false, err
	}
	return dir, true, nil
}
